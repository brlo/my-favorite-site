const RU_LIKE = ['ru', 'uk', 'be', 'kk', 'sr', 'uz', 'tk']

function detect() {
  try {
    const saved = localStorage.getItem('ui_lang')
    if (saved && dict[saved]) return saved
  } catch {}
  const nav = (navigator.language || 'ru').slice(0, 2)
  return RU_LIKE.includes(nav) ? 'ru' : 'en'
}

export const uiLang = ref(detect())

export function setUiLang(lang) {
  uiLang.value = lang
  try { localStorage.setItem('ui_lang', lang) } catch {}
}

export function t(key) {
  return dict[uiLang.value]?.[key] ?? dict.ru[key] ?? key
}

