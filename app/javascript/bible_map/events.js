// Круглая область (для предположительных мест)
function circle(lat, lon, r, n = 48) {
  const out = [];
  const k = 1 / Math.cos(lat * Math.PI / 180);
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    out.push([lat + Math.sin(a) * r, lon + Math.cos(a) * r * k]);
  }
  return out;
}

