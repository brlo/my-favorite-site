def q(text, *refs):
    """Цитата: «текст»（ссылки）; кавычки внутри цитаты становятся вложенными 『』"""
    text = text.replace('「', '『').replace('」', '』')
    return f"<blockquote><p>「{text}」（{'、'.join(refs)}）</p></blockquote>"


def src(*refs):
    return f"<p>（{'、'.join(refs)}）</p>"


def plain(work, ch, sec):
    """Текст абзаца перевода без сносок и номера: plain(ja_phil, 9, 1)"""
    p = work.CH[ch][sec - 1] if ch != 21 or work is not ja_mart else work.CH[ch][0]
    return re.sub(r'^\d+\. ', '', p.replace('[#]', ''))


# цитаты должны совпадать с текстом переводов
def check(fragment, work, ch, *secs):
    text = ''.join(plain(work, ch, s) for s in secs)
    bare = re.sub(r'</?(strong|mark|u)>', '', fragment).replace('〈…〉', '')
    for part in re.split(r'(?<=[。」])', bare):
        assert part.strip() == '' or part.strip() in text, (ch, secs, part)
    return fragment


