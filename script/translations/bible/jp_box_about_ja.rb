body = <<~HTML
  <h2>なぜ、もう一つの日本語訳が必要なのか</h2>
  <p>当サイトの日本語聖書には二つの翻訳があり、それぞれに長所があります。
  <a href="https://bibleox.com/ja/jp-ni/mk/1/">新共同訳</a>（jp-ni）は現代の生き生きとした日本語で書かれていますが、超教派的であり、
  論争のある箇所では角を丸め、時にギリシア語本文と異なる読みを採っています。
  <a href="https://bibleox.com/ja/jp-joc/mk/1/">日本正教会訳</a>（jp-joc、1901年）は正確で教会の伝統に立っていますが、
  前世紀初頭の言葉で書かれており、古い文法や旧字体、逐語的な言い回しのため、現代の日本人に必ずしも読みやすいとは限りません。</p>
  <p>この翻訳は、その二つの長所を結び合わせようとする試みです。教会の本文の正確さを、今日話されている日本語で伝えます。
  だからこそ、わざと平易にすることも、人工的に古めかしくすることもしていません。</p>

  <h2>置き換えではなく、補いとして</h2>
  <p>新しい翻訳は、既存の翻訳を置き換えるためではなく、<strong>それらを補うため</strong>のものです。
  第一の目的は、聖書の研究を助けることです。同じ節がギリシア語、教会スラヴ語、ロシア語の本文と並んで表示されるので、
  教会の読みが現代日本語にどう移されているか——原文の字句に従っているのか、文を組み替えざるを得なかったのか、
  あるいは本文そのものに異同があるのか——をたどることができます。ギリシア語や教会スラヴ語を学ぶ人には下訳としての支えとなり、
  日本語だけで読む人には正確で分かりやすい本文となります。</p>
  <p>第二の目的は、<strong>教派間の対話を容易にすること</strong>です。正教徒、カトリック、プロテスタントの間の議論は、
  聖書の意味だけでなく、翻訳や教派ごとの読み方の違いにしばしば行き着きます。ここでは教派的な改訂版ではなく教会の本文を土台とし、
  論争のある箇所は角を丸めず、読者の代わりに決着もつけません。異同は隠さず、〔…〕で示し、注で説明しています。
  だからこそ、そのたびに「自分の」翻訳に切り替えることなく、本文そのものについて語り合うことができます。</p>
  <p>この翻訳は、日本人の読者にとって新共同訳や日本正教会訳に代わるものを目指しているわけではありません。
  それぞれに意図と読者がいます。これは読むため、学ぶため、語り合うための実用的な支えとして考えられています。</p>

  <h2>どの本文に基づいているか</h2>
  <p>新約聖書では、教会が読んできた本文（ビザンティン本文。エリザベト聖書やロシア語シノドス訳と同じもの）を土台としています。
  当サイトで<a href="https://bibleox.com/ja/gr-lxx-byz/mk/1/">古代ギリシア語</a>として表示される本文は学術的な校訂版であり、
  証人の一つではあっても規範ではありません。校訂版が教会の本文と異なる箇所では、翻訳には教会の読みを採り、その異同を〔…〕で示しています。</p>
  <p>校訂版は19〜20世紀に成立し、教会が常に読んできた語句を省いている箇所がいくつかあります。
  それは後代の写字生による「挿入」ではなく、校訂版そのものの脱落です。詳しくは
  <a href="https://bibleox.com/ru/ru/w/%D0%9F%D1%80%D0%BE%D0%B1%D0%BB%D0%B5%D0%BC%D0%B0_%D0%B2%D1%81%D1%82%D0%B0%D0%B2%D0%BE%D0%BA_%D0%B2_%D0%9D%D0%BE%D0%B2%D0%BE%D0%BC_%D0%97%D0%B0%D0%B2%D0%B5%D1%82%D0%B5">「新約聖書における挿入問題」</a>（ロシア語）をご覧ください。</p>
  <p>旧約聖書は、教会が用いるギリシア語訳である七十人訳（セプトゥアギンタ）から翻訳し、教会スラヴ語本文を照合に用います。
  日本正教会訳がある箇所ではそれをギリシア語と突き合わせ、ない箇所（旧約の大部分）は新たに訳します。
  節番号は教会の数え方（七十人訳）に従い、マソラ本文と異なる場合はギリシア語の番号を保ち、シノドス訳との違いは注に記します。</p>

  <h2>どのように訳しているか</h2>
  <ul>
    <li><strong>ギリシア語から。</strong> 新共同訳は本文の典拠ではありません。著作権で保護されており、表現が自然かどうかを確かめるためだけに参照します。</li>
    <li><strong>角を丸めず、忠実に。</strong> 原文にない説明を加えず、読者の代わりに曖昧さを解消せず、意味を持つ構文はそのまま保ちます。
    七十人訳にないマソラ本文の読みは本文に取り入れず、注に記します。</li>
    <li><strong>現代日本語。</strong> 通常の文学的な日本語（だ・である体）、常用漢字、難しい語にはルビ——中学生でも読めるように。</li>
    <li><strong>用語は辞典に沿って。</strong> 重要な語（恵み、悔い改め、義、機密…）には短い説明を付けます。
    読者向けの用語辞典は別に準備中で、今は脚注で説明が見られます。</li>
    <li><strong>人名</strong>は現代の日本語聖書で用いられる形（イエス、ダビデ、アブラハム）。伝統表記ではイイスス・ハリストス。</li>
  </ul>

  <h2>読み方</h2>
  <ul>
    <li><strong>〔…〕</strong> — 校訂版にはないが、教会が読む読み。</li>
    <li><strong>赤色</strong> — イエスの言葉。</li>
    <li><strong>＊</strong> — 小さな脚注。星印にカーソルを合わせる（またはタップする）と、語の短い説明が出ます。</li>
    <li><strong>「伝統表記」ボタン</strong> — 本文上のバーにあるボタンで、一般的な語（恵み、聖霊、キリスト、パウロ）の代わりに
    伝統的な正教会の語（恩寵、聖神、ハリストス、パワェル）で表示します。</li>
  </ul>

  <h2>どこまで完成しているか</h2>
  <p>新約聖書は全27巻、7957節がそろいました。詩篇（151篇）、創世記（50章）、出エジプト記（40章）、
  コヘレトの言葉（12章）も完成しています。次は旧約聖書の残りです。まだない書は翻訳一覧に表示されます。</p>

  <h2>誰が、どのように確認しているか</h2>
  <p>草稿はAIがギリシア語本文から、日本正教会訳とロシア語シノドス訳を参照して作成し、各章を人が確認します。
  そのためページには「AI＋人間」の表示があります。誤りがあるかもしれません。お気づきの場合はサイトのチャットでお知らせください。</p>

  <h2>ライセンス</h2>
  <p>翻訳本文はパブリックドメインです。自由に複製・引用・配布できます。著作権で保護された新共同訳とはこの点が異なります。</p>
HTML

