  title: '日本語訳「ビブレオックス」',
  title_sub: '現代日本語による正教の聖書訳',
  meta_desc: '「ビブレオックス」企画による日本語聖書訳。教会の本文に基づき、現代日本語で、正教会の伝統を保って訳しています。',
