page = ::Page.find_by(lang: 'ja', path_low: PATH_JA.downcase)
if page
  page.update!(attrs)
  puts "обновлено: #{page.path}"
else
  page = ::Page.create!(attrs.merge(path: PATH_JA, user_id: 1))
  puts "создано: #{page.path}"
end

folder = ::Menu.find_or_create_by!(page_id: list.id, parent_id: ROOT_MENU_ID, title: FOLDER) { |m| m.priority = 5 }
menu = ::Menu.find_or_create_by!(page_id: list.id, parent_id: folder.id, path: page.path) do |m|
  m.title = page.title
  m.priority = 1
end
menu.update!(title: page.title, path: page.path)

puts "меню: #{FOLDER} / #{menu.title}"
