  <h2>Дополнение, а не замена</h2>
  <p>Новый перевод делается не вместо существующих, а <strong>в дополнение к ним</strong>.
  Его первая задача — облегчить изучение Библии. Читатель видит один и тот же стих рядом с греческим,
  церковнославянским и русским текстом и может проследить, как церковное чтение передаётся на современный японский:
  где перевод следует букве оригинала, где вынужден перестроить фразу, а где в самом тексте есть расхождение.
  Для изучающих греческий и церковнославянский перевод служит подстрочной опорой, а для тех, кто читает только по-японски, —
  точным и понятным текстом.</p>
  <p>Вторая задача — <strong>упростить межконфессиональный диалог</strong>. Споры между православными, католиками и протестантами
  часто упираются не в смысл Писания, а в различия переводов и конфессиональных традиций чтения.
  Здесь за основу взят церковный текст, а не конфессиональная редакция: спорные места не сглажены и не решены за читателя,
