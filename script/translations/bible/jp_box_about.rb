body = <<~HTML
  <h2>Зачем ещё один японский перевод</h2>
  <p>У японской Библии на сайте два перевода, и у каждого своя сильная сторона.
  <a href="https://bibleox.com/ru/jp-ni/mk/1/">新共同訳</a> (jp-ni) написан живым современным языком, но он межконфессиональный:
