  </ul>

  <h2>Как читать</h2>
  <ul>
    <li><strong>〔…〕</strong> — чтение, которого нет в критическом издании, но которое читает Церковь.</li>
    <li><strong>Красным</strong> выделены слова Иисуса.</li>
    <li><strong>＊</strong> — маленькая сноска: наведите курсор (или нажмите) на звёздочку, чтобы увидеть краткое объяснение слова.</li>
    <li><strong>Кнопка「伝統表記」</strong> в панели над текстом включает традиционную православную лексику
