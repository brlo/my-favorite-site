attrs = {
  title: 'Японский перевод «Библeокс»',
  title_sub: 'современный православный перевод на японский',
  meta_desc: 'Японский перевод Библии проекта «Библeокс»: основан на церковном тексте, современный язык, православная традиция.',
  body: body,
  references: references,
  page_type: 1,
  edit_mode: 1,
  is_published: true,
  is_bibleox: true,
  parent_id: list.id,
}

page = ::Page.find_by(lang: 'ru', path_low: PATH.downcase)
if page
  page.update!(attrs)
  puts "обновлено: #{page.path}"
else
  page = ::Page.create!(attrs.merge(lang: 'ru', path: PATH, user_id: 1, group_lang_id: SecureRandom.hex(12)))
  puts "создано: #{page.path}"
end

folder = ::Menu.find_or_create_by!(page_id: list.id, parent_id: 551, title: FOLDER) { |m| m.priority = 5 }
menu = ::Menu.find_or_create_by!(page_id: list.id, parent_id: folder.id, path: page.path) do |m|
  m.title = page.title
  m.priority = 1
end
menu.update!(title: page.title, path: page.path)

puts "меню: #{FOLDER} / #{menu.title}"
