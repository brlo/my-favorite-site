  Нумерация стихов — церковная (по Септуагинте): там, где она отличается от масоретской, сохранена греческая,
  а отличие от Синодального перевода указано в примечаниях.</p>

  <h2>Как мы переводим</h2>
  <ul>
    <li><strong>С греческого.</strong> 新共同訳 не источник текста: он защищён авторским правом и нужен только для проверки, естественно ли звучит фраза.</li>
    <li><strong>Верность вместо сглаживания.</strong> Мы не добавляем пояснений, которых нет в оригинале, не разрешаем за читателя двусмысленности,
    сохраняем структуру фразы, если она несёт смысл. Масоретские чтения, которых нет в Септуагинте, в текст не вносятся — они указаны в примечаниях.</li>
    <li><strong>Современный язык.</strong> Обычный литературный японский (だ・である), современные начертания иероглифов,
    фуригана над трудными словами — чтобы текст мог читать и школьник.</li>
    <li><strong>Термины — по словарю.</strong> Каждое важное слово (恵み, 悔い改め, 義, 機密…) получает короткое объяснение;
    словарь для читателя готовится отдельно, а пока пояснения видны в сносках.</li>
    <li><strong>Имена</strong> — в формах, принятых в современной японской Библии (イエス, ダビデ, アブラハム);
