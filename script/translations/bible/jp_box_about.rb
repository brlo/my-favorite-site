  а само расхождение отмечено скобками 〔…〕.</p>
  <p>Критическое издание сложилось в XIX–XX веках и в ряде мест опускает то, что Церковь читала всегда.
  Это не «вставки» позднейших переписчиков, а пропуски самого критического текста — подробнее об этом:
  <a href="https://bibleox.com/ru/ru/w/Проблема_вставок_в_Новом_Завете">Проблема вставок в Новом Завете</a>.</p>
  <p>Ветхий Завет переводится с Септуагинты — греческого перевода, которым пользуется Церковь; церковнославянский текст служит контролем.
