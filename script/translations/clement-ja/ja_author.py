def _strip(p):
    return re.sub(r'\[\d+\]', '', re.sub(r'^\d+\. ', '', p))


def _join(ch):
    return ''.join(_strip(p) for p in ALLCH[ch])


def _frag(ch, start, end=None):
    j = _join(ch)
    i = j.index(start) if start else 0
    k = j.index(end) + len(end) if end else len(j)
    return j[i:k]


