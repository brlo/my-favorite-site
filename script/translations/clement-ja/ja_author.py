def marked(par, marks, strong=True, em=False):
    tag = 'em' if em else ('strong' if strong else 'span')
    for m in marks:
        assert m in par, f'нет фрагмента: {m}'
        par = par.replace(m, f'<{tag}><mark>{m}</mark></{tag}>')
    return par


def bq(*paras):
    """Блокцитата: каждый фрагмент в своём <p>, между ними <p>…</p> (как в ru)"""
    return '<blockquote>' + '<p>…</p>'.join(f'<p>{p}</p>' for p in paras) + '</blockquote>'


